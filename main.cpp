#include <string>
#include <vector>

void power_of_two() {
    unsigned int n = 64u;
    bool is_power = (n != 0u) && ((n & (n - 1u)) == 0u);
    (void)is_power;
}

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

void is_palindrome() {
    std::string text = "level";
    bool palindrome = true;
    for (std::size_t i = 0; i < text.size() / 2; ++i) {
        if (text[i] != text[text.size() - 1 - i]) { palindrome = false; break; }
    }
    (void)palindrome;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

extern "C" int bright_summit();
extern "C" void still_delta();
extern "C" void cobalt_spruce();

int main() {
    power_of_two();
    swap_values();
    is_palindrome();
    is_prime();
    still_delta();
    cobalt_spruce();
    return bright_summit();
}
